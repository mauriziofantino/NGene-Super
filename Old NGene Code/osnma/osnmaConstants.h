/******/
/* Constants referred to Galileo navigation message format */
/**
 * @def GAL_PAGES_PER_SUBFRAME
 * @brief In one subframe we have 15 pages, each made of two page parts
 */
#define GAL_PAGES_PER_SUBFRAME  15

/**
 * @def GAL_SECONDS_PER_PAGE
 * @brief One Galileo page (word) lasts 2 seconds
 */
#define GAL_SECONDS_PER_PAGE  2

/**
 * @def GAL_SECONDS_PER_SUBFRAME
 * @brief One Galileo subframe lasts 30 seconds
 */
#define GAL_SECONDS_PER_SUBFRAME  30

/**
 * @def GAL_BYTES_PER_SUBFRAME
 * @brief One Galileo subframe is made of 450 bytes
 *        (i.e. GAL_DECODED_PAGE_PART_LENGTH_BYTES * number of page parts * GAL_PAGES_PER_SUBFRAME = 15*2*15)
 */
#define GAL_BYTES_PER_SUBFRAME  450


/******/
/* Constants referred to OSNMA formats */
/* Size expressed in bytes */
/**
 * @def OSNMA_PER_SUBFRAME_SIZE
 * @brief Number of bytes reserved to OSNMA in one subframe i.e. 40 bits * 15 words (in bytes)
 */
#define OSNMA_PER_SUBFRAME_SIZE 75


/**
 * @def HKROOT_PER_WORD_SIZE
 * @brief Number of bytes reserved to HKROOT in one word (in bytes)
 */
#define HKROOT_PER_WORD_SIZE 1

/**
 * @def HKROOT_PER_SUBFRAME_SIZE
 * @brief Number of bytes in one HKROOT section, i.e. one subframe (headers included) i.e. 8 bits * 15 words (headers included) (in bytes)
 */
#define HKROOT_PER_SUBFRAME_SIZE 15

/**
 * @def DSM_BLOCK_SIZE
 * @brief Number of bytes in one DSM block, i.e. one subframe (headers excluded). (in bytes)
 */
#define DSM_BLOCK_SIZE	13


/**
 * @def MACK_PER_WORD_SIZE
 * @brief Number of bytes reserved to MACK in one word (in bytes)
 */
#define MACK_PER_WORD_SIZE 4

/**
 * @def MACK_PER_SUBFRAME_SIZE
 * @brief Number of bytes reserved to MACK in one subframe i.e. 32 bits * 15 words (in bytes)
 */
#define MACK_PER_SUBFRAME_SIZE 60




