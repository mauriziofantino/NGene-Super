/** Convert packed transmission order to reliable signed soft symbols. */
static void Unpack(const uint8_t *bytes, int8_t *out, size_t count, int invert)
{
    for (size_t i = 0; i < count; ++i) {
        const int bit = ((bytes[i / 8] >> (7u - i % 8)) & 1) ^ invert;
        out[i] = bit ? -100 : 100;
    }
}

/** Check decoded fields and the complete packed subframes. */
static void CheckPayload(const TNgBcnv1Frame *frame, int inverted)
{
    CHECK(frame->prn == 33 && frame->soh == 199 && frame->inverted == inverted);
    CHECK(frame->week == 2047 && frame->hour == 167 && frame->iodc == 513 && frame->iode == 97);
    CHECK(frame->pageId == 3 && frame->health == 1);
    CHECK(frame->dif == 1 && frame->sif == 0 && frame->aif == 1 && frame->sismai == 9);
    CHECK(memcmp(frame->sf2, expectedSf2, sizeof(expectedSf2)) == 0);
    CHECK(memcmp(frame->sf3, expectedSf3, sizeof(expectedSf3)) == 0);
}

/** Despread synthetic B1C data with the aligned pilot's code/carrier timing. */
static void CheckDataBridge(void)
{
    enum { count = 20480 };
    int8_t data[NG_BEIDOU_B1C_LENGTH], pilot[NG_BEIDOU_B1C_LENGTH];
    int8_t expected[NG_BCNV1_FRAME_SYMBOLS], observed[NG_BCNV1_FRAME_SYMBOLS];
    float *replica = calloc(count, sizeof(*replica));
    float *pilotQ = calloc(count, sizeof(*pilotQ));
    TNgComplex *iq = calloc(count, sizeof(*iq));
    TNgBcnv1Frame frame;
    CHECK(replica && iq && pilotQ);
    CHECK(NgBeidouB1cGenerate(33, NG_BEIDOU_B1C_DATA, data, NULL) == NG_OK);
    CHECK(NgBeidouB1cGenerate(33, NG_BEIDOU_B1C_PILOT, pilot, NULL) == NG_OK);
    Unpack(clean, expected, NG_BCNV1_FRAME_SYMBOLS, 1);
    for (size_t k = 0; k < count; ++k) {
        const uint64_t phase = (uint64_t)k * NG_BEIDOU_B1C_SUBCHIPS *
                               NG_BEIDOU_B1C_RATE_HZ / 2048000u;
        const TNgComplex p = NgBeidouB1cPilotAt(pilot, phase);
        replica[k] = 2 * NgBeidouB1cDataAt(data, phase);
        pilotQ[k] = p.q;
    }
    for (unsigned bit = 0; bit < NG_BCNV1_FRAME_SYMBOLS; ++bit) {
        double i, q;
        const float sign = expected[bit] < 0 ? -0.5f : 0.5f;
        for (size_t n = 0; n < count; ++n) {
            /* Use the BOC(1,1) projection of the pilot in Q and the data branch in I. */
            iq[n].i = sign * replica[n];
            iq[n].q = pilotQ[n];
        }
        NgSearchCorrelate(iq, replica, count, 1, &i, &q);
        CHECK(i != 0 && (i < 0) == (expected[bit] < 0));
        observed[bit] = (int8_t)(100 * i / count);
    }
    CHECK(NgBcnv1Decode(observed, 33, &frame) == NG_OK);
    CheckPayload(&frame, 1);
    free(iq);
    free(pilotQ);
    free(replica);
}

/** The production tracker must turn complete primary periods into B-CNAV1 symbols. */
static void CheckTrackedFrame(void)
{
    enum { count = 20480, warmup = 120 };
    int8_t chips[NG_BEIDOU_B1C_LENGTH], pilot[NG_BEIDOU_B1C_LENGTH];
    int8_t symbols[NG_BCNV1_SYNC_SYMBOLS];
    TNgIq8 replica[count], block[count];
    TNgTrackingConfig config;
    TNgTracking *tracking = NULL;
    TNgTrackingSnapshot snapshot;
    TNgStreamInfo stream = {0};
    TNgIqView window = {0};
    TNgAcquisitionResult seed = {0};
    TNgError error = {{0}};
    NgTrackingDefaults(&config);
    stream.sampleRateHz = 2048000;
    stream.format = NG_FORMAT_CI8;
    seed.prn = 33;
    seed.confirmed = 1;
    seed.epoch = 5;
    CHECK(NgBeidouB1cGenerate(seed.prn, NG_BEIDOU_B1C_DATA, chips, &error) == NG_OK);
    CHECK(NgBeidouB1cGenerate(seed.prn, NG_BEIDOU_B1C_PILOT, pilot, &error) == NG_OK);
    CHECK(NgTrackingCreate(&config, &stream, NG_CONSTELLATION_BEIDOU, &tracking, &error) == NG_OK);
    CHECK(NgTrackingSeed(tracking, &seed, &error) == NG_OK);
    Unpack(clean, symbols, NG_BCNV1_FRAME_SYMBOLS, 0);
    Unpack(nextHeader, symbols + NG_BCNV1_FRAME_SYMBOLS, NG_BCNV1_HEADER_SYMBOLS, 0);
    for (unsigned n = 0; n < count; ++n) {
        uint64_t phase = (uint64_t)n * NG_BEIDOU_B1C_SUBCHIPS * NG_BEIDOU_B1C_RATE_HZ /
                         stream.sampleRateHz;
        replica[n].i = (int8_t)(100 * NgBeidouB1cDataAt(chips, phase));
        replica[n].q = (int8_t)(100 * NgBeidouB1cPilotAt(pilot, phase).q);
    }
    window.format = NG_FORMAT_CI8;
    window.meta.epoch = seed.epoch;
    window.meta.count = count;
    window.samples = block;
    for (unsigned period = 0; period < warmup + NG_BCNV1_SYNC_SYMBOLS; ++period) {
        int sign = (period >= warmup && symbols[period - warmup] < 0) ? -1 : 1;
        for (unsigned n = 0; n < count; ++n) {
            block[n].i = (int8_t)(replica[n].i * sign);
            block[n].q = period % 2 ? (int8_t)-replica[n].q : replica[n].q;
        }
        window.meta.firstSample = (uint64_t)period * count;
        CHECK(NgTrackingProcess(tracking, &window, &error) == NG_OK);
    }
    NgTrackingRead(tracking, &snapshot);
    CHECK(snapshot.active && snapshot.pll && snapshot.prn == 33);
    CHECK(snapshot.navigation.validSubframes == 1);
    CHECK(!snapshot.navigation.towValid); /* The fixture carries unhealthy, unmatched data. */
    NgTrackingDestroy(tracking);
}

/** Verify sliding framing and original sample timing after both forms of discontinuity. */
static void CheckStream(const int8_t *symbols, size_t prefix, int inverted)
{
    TNgBcnv1Stream stream = {0};
    TNgBcnv1Frame frame;
    const uint64_t first = UINT64_C(9007199254740993);
    uint64_t sample = first, anchor = 0;
    for (size_t n = 0; n < prefix + NG_BCNV1_SYNC_SYMBOLS; ++n) {
        const uint64_t end = sample + 20480 + n % 2;
        const int result = NgBcnv1Push(&stream, 33, 7, sample, end, symbols[n],
                                      &frame, &anchor);
        CHECK(result == (n + 1 == prefix + NG_BCNV1_SYNC_SYMBOLS ? NG_OK : NG_END));
        sample = end;
    }
    CheckPayload(&frame, inverted);
    CHECK(anchor == first + 20480 * prefix + prefix / 2);
    CHECK(stream.elapsedSymbols == NG_BCNV1_SYNC_SYMBOLS);
    for (size_t n = NG_BCNV1_HEADER_SYMBOLS; n < NG_BCNV1_FRAME_SYMBOLS; ++n) {
        const uint64_t end = sample + 20480 + (prefix + NG_BCNV1_FRAME_SYMBOLS + n) % 2;
        const int result = NgBcnv1Push(&stream, 33, 7, sample, end, symbols[prefix + n],
                                      &frame, &anchor);
        CHECK(result == (n + 1 == NG_BCNV1_FRAME_SYMBOLS ? NG_OK : NG_END));
        sample = end;
    }
    CHECK(frame.soh == 0 && stream.elapsedSymbols == NG_BCNV1_FRAME_SYMBOLS);
    size_t next = prefix + NG_BCNV1_FRAME_SYMBOLS;
    CHECK(anchor == first + 20480 * next + next / 2);
    CHECK(NgBcnv1Push(&stream, 33, 7, sample + 1, sample + 20481, 80,
                       &frame, &anchor) == NG_END && stream.count == 1);
    CHECK(NgBcnv1Push(&stream, 33, 8, sample + 20481, sample + 40961, 80,
                       &frame, &anchor) == NG_END && stream.count == 1);
}

/** Test header error correction, both FEC paths, both CRCs and wrapped SOH alignment. */
int main(void)
{
    CheckTrackedFrame();
    enum { prefix = 19, span = prefix + NG_BCNV1_FRAME_SYMBOLS + NG_BCNV1_HEADER_SYMBOLS };
    int8_t symbols[span];
    TNgBcnv1Frame frame;
    size_t offset = 0;
    for (int inverted = 0; inverted <= 1; ++inverted) {
        memset(symbols, 80, sizeof(symbols));
        int8_t *start = symbols + prefix;
        Unpack(clean, start, NG_BCNV1_FRAME_SYMBOLS, inverted);
        Unpack(nextHeader, start + NG_BCNV1_FRAME_SYMBOLS, NG_BCNV1_HEADER_SYMBOLS, inverted);
        CHECK(NgBcnv1Find(symbols, span, 33, &offset, &frame) == NG_OK && offset == prefix);
        CheckPayload(&frame, inverted);
        CHECK(frame.correctedBits[0] == 0 && frame.correctedBits[1] == 0 &&
              frame.correctedBits[2] == 0);
        CheckStream(symbols, prefix, inverted);
        CHECK(NgBcnv1Find(symbols, span - 1, 33, &offset, &frame) == NG_END);
        Unpack(nextHeader, start + NG_BCNV1_FRAME_SYMBOLS, NG_BCNV1_HEADER_SYMBOLS, !inverted);
        CHECK(NgBcnv1Find(symbols, span, 33, &offset, &frame) == NG_END);
        CHECK(NgBcnv1Decode(start, 34, &frame) == NG_END);
        CHECK(NgBcnv1Decode(start, 0, &frame) == NG_ERROR);

        start[0] = (int8_t)-start[0];
        start[30] = (int8_t)-start[30];
        const unsigned flips[] = {72, 72 + 36, 72 + 2, 72 + 2 + 36};
        for (unsigned k = 0; k < sizeof(flips) / sizeof(*flips); ++k)
            start[flips[k]] = start[flips[k]] < 0 ? 8 : -8;
        CHECK(NgBcnv1Decode(start, 33, &frame) == NG_OK);
        CheckPayload(&frame, inverted);
        CHECK(frame.correctedBits[0] == 2 && frame.correctedBits[1] == 2 &&
              frame.correctedBits[2] == 2);
    }
    const uint8_t *invalid[] = {badSf2, badSf3};
    const TNgBcnv1Frame previous = frame;
    for (unsigned k = 0; k < sizeof(invalid) / sizeof(*invalid); ++k) {
        Unpack(invalid[k], symbols, NG_BCNV1_FRAME_SYMBOLS, 0);
        CHECK(NgBcnv1Decode(symbols, 33, &frame) == NG_END);
        CHECK(frame.soh == previous.soh && frame.inverted == previous.inverted);
    }
    Unpack(clean, symbols, NG_BCNV1_FRAME_SYMBOLS, 0);
    memset(symbols + NG_BCNV1_HEADER_SYMBOLS, 0,
           NG_BCNV1_FRAME_SYMBOLS - NG_BCNV1_HEADER_SYMBOLS);
    CHECK(NgBcnv1Decode(symbols, 33, &frame) == NG_END);
    CheckDataBridge();
    puts("B-CNAV1 framing, polarity, BCH, joint interleaver, GF64 LDPC and both CRC gates verified");
    return 0;
}
